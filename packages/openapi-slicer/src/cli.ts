import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { slice, tagFile, danglingRefs, extractOperation } from './slice.ts';

const DEFAULT_URL = 'https://git.cafe/api/openapi/json';
const args = process.argv.slice(2);
const flag = (n: string) => {
  const i = args.indexOf(`--${n}`);
  return i >= 0 ? args[i + 1] : undefined;
};
const outDir = flag('out') ?? 'out/openapi';
const input = flag('input');

const raw = input
  ? await readFile(input, 'utf8')
  : await (async () => {
      const res = await fetch(flag('url') ?? DEFAULT_URL, { headers: { 'user-agent': 'gitcafe-agent-kit/0.1 (openapi-slicer)' } });
      if (!res.ok) throw new Error(`spec fetch failed: ${res.status}`);
      return res.text();
    })();

const spec = JSON.parse(raw);
const lockPath = flag('lock') ?? 'packages/openapi-slicer/operation-id.lock.json';
const lockIn = await readFile(lockPath, 'utf8').then(JSON.parse, () => ({}));
const { slices, ops, renameMap, lock } = slice(spec, lockIn);
await writeFile(lockPath, JSON.stringify(Object.fromEntries(Object.entries(lock).sort(([a], [b]) => a.localeCompare(b))), null, 1) + '\n');
const approxTokens = (n: number) => Math.round(n / 4);

await mkdir(join(outDir, 'by-tag'), { recursive: true });
const tagRows: { tag: string; file: string; operations: number; chars: number }[] = [];
for (const [tag, doc] of slices) {
  const bad = danglingRefs(doc);
  if (bad.length) throw new Error(`slice ${tag} has dangling refs: ${bad.slice(0, 3).join(', ')}`);
  const text = JSON.stringify(doc, null, 1);
  const file = `by-tag/${tagFile(tag)}.json`;
  await writeFile(join(outDir, file), text);
  tagRows.push({ tag, file, operations: ops.filter((o) => o.tag === tag).length, chars: text.length });
}

await mkdir(join(outDir, 'ops'), { recursive: true });
const opChars: Record<string, number> = {};
for (const o of ops) {
  if (o.webhook) continue;
  const doc = extractOperation(slices.get(o.tag), o.path, o.method);
  const text = JSON.stringify(doc, null, 1);
  opChars[o.id] = text.length;
  await writeFile(join(outDir, 'ops', `${o.id}.json`), text);
}
ops.sort((a, b) => a.tag.localeCompare(b.tag) || a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
await writeFile(join(outDir, 'operation-id-map.json'), JSON.stringify(renameMap, null, 1));
await writeFile(join(outDir, 'index.json'), JSON.stringify({ source: input ?? flag('url') ?? DEFAULT_URL, specChars: raw.length, tags: tagRows, operations: ops }));

const md: string[] = [
  '# Git.cafe API index',
  '',
  `Operations: ${ops.length}. Load one slice from \`by-tag/\` only after picking an operation here. Format: \`operationId METHOD path — summary\``,
  '',
];
for (const t of tagRows) {
  md.push(`## ${t.tag} (\`${t.file}\`)`);
  for (const o of ops.filter((o) => o.tag === t.tag)) md.push(`${o.id} ${o.method} ${o.path} — ${o.summary}`);
  md.push('');
}
const indexMd = md.join('\n');
await writeFile(join(outDir, 'INDEX.md'), indexMd);

const largest = [...tagRows].sort((a, b) => b.chars - a.chars)[0];
const stats = {
  fullSpecChars: raw.length,
  indexChars: indexMd.length,
  largestSlice: { tag: largest.tag, chars: largest.chars },
  approxTokens: { full: approxTokens(raw.length), index: approxTokens(indexMd.length), largestSlice: approxTokens(largest.chars) },
};
await writeFile(join(outDir, 'stats.json'), JSON.stringify(stats, null, 1));
console.log(JSON.stringify({ operations: ops.length, tags: tagRows.length, ...stats }, null, 1));

const showcase = ['listPullRequests', 'getPullRequest', 'createPullRequest', 'mergePullRequest', 'closePullRequest', 'listIssues', 'createIssue', 'unlockIssue', 'listRepositories', 'getRepository', 'listRepoActionRuns', 'createOrgActionRunnerRegistrationToken'];
const byId = new Map(ops.map((o) => [o.id, o]));
const rows = showcase.filter((id) => byId.has(id)).map((id) => `| \`${byId.get(id)!.was}\` | \`${id}\` | ${byId.get(id)!.method} \`${byId.get(id)!.path}\` |`);
const longest = [...ops].filter((o) => !o.webhook).sort((a, b) => b.was.length - a.was.length)[0];
const report = `# Before / after

Generated by \`pnpm slice\` from ${input ?? flag('url') ?? DEFAULT_URL}.

## operationId

| before | after | operation |
| --- | --- | --- |
${rows.join('\n')}

Longest original id: \`${longest.was}\` (${longest.was.length} chars) → \`${longest.id}\`.
REST operations renamed: ${ops.filter((o) => !o.webhook && o.id !== o.was).length} of ${ops.filter((o) => !o.webhook).length}; webhook event ids (\`webhooks.issueCreated\`) are kept as-is.

## What an agent has to load

| artifact | chars | ≈ tokens (chars/4) |
| --- | ---: | ---: |
| full spec | ${raw.length.toLocaleString('en')} | ${stats.approxTokens.full.toLocaleString('en')} |
| largest slice (${largest.tag}) | ${largest.chars.toLocaleString('en')} | ${stats.approxTokens.largestSlice.toLocaleString('en')} |
| INDEX.md (all ${ops.length} operations) | ${indexMd.length.toLocaleString('en')} | ${stats.approxTokens.index.toLocaleString('en')} |
| \`ops/listPullRequests.json\` (one operation) | ${opChars.listPullRequests?.toLocaleString('en')} | ${approxTokens(opChars.listPullRequests ?? 0).toLocaleString('en')} |
| median single operation | ${Object.values(opChars).sort((a, b) => a - b)[Math.floor(Object.keys(opChars).length / 2)].toLocaleString('en')} | ${approxTokens(Object.values(opChars).sort((a, b) => a - b)[Math.floor(Object.keys(opChars).length / 2)]).toLocaleString('en')} |
| median slice | ${[...tagRows].sort((a, b) => a.chars - b.chars)[Math.floor(tagRows.length / 2)].chars.toLocaleString('en')} | ${approxTokens([...tagRows].sort((a, b) => a.chars - b.chars)[Math.floor(tagRows.length / 2)].chars).toLocaleString('en')} |

Token numbers are a chars/4 estimate, not a tokenizer count.
`;
await writeFile(join(outDir, 'BEFORE_AFTER.md'), report);
